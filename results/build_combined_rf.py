"""Combine pixel temp x veg surface features with the sector covariates in an RF.

Adds to the ENV(10)+terrain set:
  - leak-free pixel features: pop-weighted MODIS temp/NDVI/EVI means,
    warm_lowveg_frac (temp>=21 & NDVI<=0.5 = high-risk corner of the learned
    surface), ndvi_std (within-sector heterogeneity);
  - suit_oof: the learned S(temp,NDVI) suitability, generated by CROSS-FITTING
    (ridge re-fit on each LODO training fold) so it carries no target leakage.
Evaluate RF leave-one-district-out vs the baseline.
"""
import numpy as np, xarray as xr, pandas as pd
import rasterio.features as rfeat
from sklearn.ensemble import RandomForestRegressor
from sklearn.linear_model import Ridge
from sklearn.model_selection import LeaveOneGroupOut
from sklearn.base import clone
from scipy.stats import spearmanr
import chap_gis as cgis
from chap_gis.cli.dynamic import prepare_boundaries
from chap_gis.grid import reproject_population_to

# ---- pixel grid (MODIS temp/NDVI) ----
ds = xr.open_dataset("results/veg_temp_2021/stack.nc")
tann = ds["temperature"].mean("month").rio.write_crs("EPSG:4326")
nann = ds["ndvi"].mean("month").rio.write_crs("EPSG:4326")
eann = ds["evi"].mean("month").rio.write_crs("EPSG:4326")
T, Nd, Ev = (a.values.astype(np.float32) for a in (tann, nann, eann))
shp = T.shape
gdf = prepare_boundaries("RWA", 5); NS = len(gdf); loc = gdf["location_id"].to_numpy()
sect = rfeat.rasterize(((g, i) for i, g in enumerate(gdf.geometry)),
        out_shape=shp, transform=tann.rio.transform(), fill=-1, dtype="int32")
wp = cgis.io.worldpop.load(country_code="RWA", start=2021, end=2021).squeeze(drop=True)
wp.rio.write_crs("EPSG:4326", inplace=True)
pop = reproject_population_to(wp, tann, "bilinear").values.astype(np.float32)
if pop.ndim == 3: pop = pop[0]

ok = (sect >= 0) & np.isfinite(T) & np.isfinite(Nd) & np.isfinite(Ev) & np.isfinite(pop) & (Nd > -1)
s = sect[ok]; w = pop[ok].astype(np.float64)
wsum = np.bincount(s, weights=w, minlength=NS); cnt = np.bincount(s, minlength=NS)
def wmean(arr): return np.bincount(s, weights=w*arr[ok].astype(np.float64), minlength=NS)/np.maximum(wsum,1)
warm_low = ((T >= 21) & (Nd <= 0.5)).astype(np.float64)
pix = pd.DataFrame({
    "location_id": loc,
    "modis_temp": wmean(T), "modis_ndvi": wmean(Nd), "modis_evi": wmean(Ev),
    "warm_lowveg_frac": np.bincount(s, weights=w*warm_low[ok], minlength=NS)/np.maximum(wsum,1),
    "ndvi_std": np.sqrt(np.maximum(wmean(Nd**2)-wmean(Nd)**2, 0)),
}).set_index("location_id")

# per-sector 2D (temp,NDVI) histogram for the learned-suitability cross-fit
TB = np.linspace(10,26,11); NBv = np.linspace(0,0.9,9); NT,NN=len(TB)-1,len(NBv)-1
ti=np.clip(np.digitize(T,TB)-1,0,NT-1); ni=np.clip(np.digitize(Nd,NBv)-1,0,NN-1)
H=np.bincount(s*(NT*NN)+ti[ok]*NN+ni[ok], weights=w, minlength=NS*NT*NN).reshape(NS,NT,NN)
Hn=(H/np.clip(H.sum((1,2),keepdims=True),1,None)).reshape(NS,-1)

# ---- sector covariates ----
cov=pd.read_csv("data/inputs/chap_data_level5_clean_2013-2021.csv").rename(columns={"location":"location_id"})
cov["location_id"]=cov["location_id"].astype(str)
ENV=["mean_temperature","max_temperature","min_temperature","dewpoint_temperature",
     "relative_humidity","rainfall_era5","rainfall_chirps","rainfall_iri","evi","ndvi"]
sec=cov.groupby("location_id")[ENV].mean()
terr=pd.read_csv("results/rwanda_sector_terrain.csv").set_index("location_id")
tgt=pd.read_csv("results/rwanda_sector_control_temp.csv").set_index("location_id")["annual_incidence_per1000"]
g=cgis.io.boundaries.load("RWA",level=5)[["shapeID","parent"]]; g["location_id"]=g.shapeID.astype(str)
par=g.set_index("location_id")["parent"]

df=sec.join(terr).join(pix).join(tgt).join(par)
df=df[df["annual_incidence_per1000"].notna() & df["parent"].notna()]
df=df[(H.sum((1,2))[[list(loc).index(x) for x in df.index]])>0]
y=df["annual_incidence_per1000"].values; groups=df["parent"].astype(str).values
TERR=["elevation_m","rice_frac","wetland_frac","water_frac"]
PIX=["modis_temp","modis_ndvi","modis_evi","warm_lowveg_frac","ndvi_std"]
Hdf=Hn[[list(loc).index(x) for x in df.index]]
print(f"sectors={len(df)}", flush=True)

logo=LeaveOneGroupOut()
# cross-fitted learned suitability (leak-free OOF)
suit_oof=np.full(len(y),np.nan)
for tr,te in logo.split(Hdf,y,groups):
    suit_oof[te]=clone(Ridge(alpha=5.0)).fit(Hdf[tr],y[tr]).predict(Hdf[te])
df["suit_surface"]=suit_oof

def rf_lodo(cols):
    X=df[cols].fillna(df[cols].mean()).values; pred=np.full(len(y),np.nan)
    for tr,te in logo.split(X,y,groups):
        pred[te]=RandomForestRegressor(n_estimators=600,min_samples_leaf=3,random_state=0,n_jobs=-1).fit(X[tr],y[tr]).predict(X[te])
    return spearmanr(pred,y).statistic

print("\n=== RF leave-one-district-out Spearman vs incidence ===")
sets={
 "ENV+terrain (baseline)": ENV+TERR,
 "+ pixel feats":          ENV+TERR+PIX,
 "+ learned S(temp,NDVI)": ENV+TERR+["suit_surface"],
 "+ pixel feats + S":      ENV+TERR+PIX+["suit_surface"],
}
for n,c in sets.items(): print(f"  {n:26}{rf_lodo(c):.3f}")
print("  (refs: ENV+terrain was 0.74 ; pixel S(temp,NDVI) alone 0.669)")

rf=RandomForestRegressor(n_estimators=600,min_samples_leaf=3,random_state=0,n_jobs=-1).fit(
    df[ENV+TERR+PIX+["suit_surface"]].fillna(df[ENV+TERR+PIX+["suit_surface"]].mean()).values, y)
imp=pd.Series(rf.feature_importances_,index=ENV+TERR+PIX+["suit_surface"]).sort_values(ascending=False)
print("\nRF importances (full combined set):"); print(imp.round(3).head(12).to_string())
